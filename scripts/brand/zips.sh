#!/usr/bin/env bash
# Builds the downloadable ZIP packs from public/brand (run after build.py and render.py).
set -euo pipefail
cd "$(dirname "$0")/../../public/brand"
rm -rf zips && mkdir zips
cat > /tmp/README-brand.txt <<'T'
BeigeLeads brand assets (v1.0, November 2026)
Use the logo as supplied: do not recolour, stretch, rotate or add effects. See guidelines/beigeleads-brand-guidelines.pdf.
Colours: Forest 900 #0f2a1d, Forest 700 #1b4332, Forest 500 #2d6a4f, Forest 300 #8fd0a9, Sand 50 #fbf8f1, Sand 200 #e8dec6, Purple 600 #7c3aed (buttons only).
Font: Bricolage Grotesque (SIL Open Font License). Questions: https://beigeleads.com/contact
T
zip -qr -X zips/beigeleads-logo-pack.zip svg png -x '*/.DS_Store'
zip -qr -X zips/beigeleads-favicon-pack.zip favicon
zip -qr -X zips/beigeleads-social-assets.zip social email
zip -qr -X zips/beigeleads-brand-kit.zip svg png favicon social email guidelines
mkdir -p /tmp/zr && cp /tmp/README-brand.txt /tmp/zr/README.txt
for z in zips/*.zip; do zip -qj -X "$z" /tmp/zr/README.txt; done
ls -l zips
# Real file sizes and counts for the media-kit page (no invented numbers).
python3 - <<'PY'
import os, zipfile, json
root = "."
def size(p): return os.path.getsize(p)
files = {}
for d, _, fs in os.walk("."):
    for f in fs:
        if d.startswith("./zips"): continue
        p = os.path.join(d, f)[2:]; files[p] = size(p)
zips = {}
for z in sorted(os.listdir("zips")):
    with zipfile.ZipFile("zips/" + z) as zf: zips[z] = {"bytes": size("zips/" + z), "files": len(zf.namelist())}
out = "../../lib/media-kit/manifest.ts"
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write("// GENERATED by scripts/brand/zips.sh. Do not edit by hand.\nexport const BRAND_FILES: Record<string, number> = " + json.dumps(files, indent=1, sort_keys=True) + ";\nexport const BRAND_ZIPS: Record<string, { bytes: number; files: number }> = " + json.dumps(zips, indent=1) + ";\n")
PY
