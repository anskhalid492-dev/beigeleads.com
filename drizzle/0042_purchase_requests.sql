-- Team Purchase Requests (CLAUDE.md section 114). Run ONE statement per message in D1 Studio.
CREATE TABLE purchase_requests (
  id integer PRIMARY KEY AUTOINCREMENT NOT NULL,
  reference text NOT NULL,
  token_hash text NOT NULL,
  requester_name text NOT NULL,
  requester_email text NOT NULL,
  manager_name text NOT NULL DEFAULT '',
  manager_email text NOT NULL,
  note text NOT NULL DEFAULT '',
  items_json text NOT NULL,
  subtotal_cents integer NOT NULL,
  discount_cents integer NOT NULL DEFAULT 0,
  total_cents integer NOT NULL,
  dedupe_key text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  created_at integer NOT NULL DEFAULT (unixepoch()),
  expires_at integer NOT NULL,
  viewed_at integer,
  decided_at integer,
  decline_reason text,
  order_id text,
  reminder_at integer,
  expired_notified_at integer,
  paid_notified_at integer,
  requester_email_status text NOT NULL DEFAULT 'pending',
  manager_email_status text NOT NULL DEFAULT 'pending',
  UNIQUE (reference),
  UNIQUE (token_hash),
  UNIQUE (dedupe_key)
);
